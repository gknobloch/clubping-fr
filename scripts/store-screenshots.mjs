// ---------------------------------------------------------------------------
// Store screenshots (#520)
//
// The five images a store listing shows are captured, not hand-taken: this
// drives the review account (REVIEW_LOGIN_EMAIL / REVIEW_LOGIN_CODE — the same
// bypass that lets App Store and Play reviewers sign in, see auth.ts) through
// mobile/.maestro/screenshots/capture.yaml on a real simulator and a real
// emulator, and drops the PNGs where `deliver` and `supply` already expect
// them (mobile/fastlane/…), both currently switched off in the Fastfile until
// there is something real to upload.
//
// Maestro rather than fastlane's own `snapshot`/`screengrab`: both need a test
// target INSIDE ios/ or android/ (XCUITest, Espresso), and those directories
// are gitignored and regenerated by `expo prebuild` — which this script also
// runs, being the fix for the stale-directory trap #495 paid for once already.
// A test target added there would not survive the next one. Maestro drives the
// installed app from outside, so it has nothing to lose.
//
// This is NOT part of a release. It is manual, run only when a captured
// screen's content has visibly changed — mobile-release does not call it.
//
// What is pure enough to test lives here as exported functions; the rest is
// shelling out to Xcode, an Android emulator and Maestro, none of which a unit
// test can stand in for. That part is proven by running it, the same way every
// other piece of this app's native surface has been.
// ---------------------------------------------------------------------------

import { execFileSync, spawn } from 'node:child_process'
import { mkdirSync, readFileSync, readdirSync, copyFileSync, rmSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const MOBILE = path.join(ROOT, 'mobile')
const FLOW = path.join(MOBILE, '.maestro/screenshots/capture.yaml')

// Names match the five files already in the repo — see capture.yaml for why.
export const REQUIRED_SCREENS = ['01-accueil', '02-journees', '04-equipes', '05-joueurs']
// Only rendered for a captain with an upcoming match (NextMatchCard's
// `isCaptain`) — which club member the review account happens to be is a fact
// about the production database, not something this script controls.
export const OPTIONAL_SCREENS = ['03-composition']

/**
 * A capture target: one platform, one device class, one destination.
 *
 * `resolveDevice` is looked up at run time rather than a stored id — a
 * simulator's UDID is specific to the Mac it was created on, and committing
 * one would work once, on one machine, and nowhere else.
 */
const TARGETS = [
  {
    id: 'iphone',
    platform: 'ios',
    // "6.9-inch" is Apple's current largest phone class — whichever model
    // that is stays "Pro Max", so matching the name rather than a version
    // keeps working as new hardware ships.
    simulatorName: 'iPhone 17 Pro Max',
    destDir: path.join(MOBILE, 'fastlane/screenshots/fr-FR'),
    // Prefixed: the iPad target writes into the SAME locale folder (deliver
    // buckets iOS screenshots by pixel size, not by folder), so both cannot
    // use the bare "01-accueil.png" or one overwrites the other.
    filePrefix: 'iphone_',
  },
  {
    id: 'ipad',
    platform: 'ios',
    simulatorName: 'iPad Pro 13-inch (M5)',
    destDir: path.join(MOBILE, 'fastlane/screenshots/fr-FR'),
    filePrefix: 'ipad_',
  },
  {
    id: 'android',
    platform: 'android',
    // Matches the phone the five committed screenshots were already shot on
    // (1080x1920 — see git history). Play does not require a tablet set the
    // way Apple requires iPad for a supportsTablet app, so there is no
    // Android tablet target here.
    avdNamePrefix: 'Medium_Phone',
    destDir: path.join(MOBILE, 'fastlane/metadata/android/fr-FR/images/phoneScreenshots'),
    filePrefix: '',
  },
]

