function androidHome() {
  const home = process.env.ANDROID_HOME || path.join(process.env.HOME, 'Library/Android/sdk')
  if (!existsSync(home)) {
    throw new Error(`ANDROID_HOME introuvable (${home}). SDK Android requis pour la cible android.`)
  }
  return home
}

/**
 * Prebuild + build + install the app once for a platform, before its
 * target(s) run. Idempotent: a second call after the first is a fast
 * incremental Xcode/Gradle build, not a full rebuild.
 */
function buildFor(platform) {
  console.log(`→ expo prebuild --clean -p ${platform}`)
  sh('npx', ['expo', 'prebuild', '--clean', '-p', platform], { cwd: MOBILE, stdio: 'inherit' })
}

/** UTF8_ENV, plus whatever the caller adds — ANDROID_HOME, a custom PATH. */
function envWith(extra) {
  return { ...UTF8_ENV, ...extra }
}

function installAndLaunchIos(udid) {
  bootIosSimulator(udid)
  console.log(`→ expo run:ios --configuration Release --device ${udid}`)
  // --no-bundler: a Release build carries its own bundle, and leaving Metro
  // running invites the app to be pointed at it instead — which would decide
  // what the screenshots show from outside the binary being shipped.
  sh('npx', ['expo', 'run:ios', '--configuration', 'Release', '--no-bundler', '--device', udid], {
    cwd: MOBILE, stdio: 'inherit',
  })
}

function installAndLaunchAndroid(avdNamePrefix) {
  const home = androidHome()
  const env = envWith({
    ANDROID_HOME: home,
    PATH: `${path.join(home, 'platform-tools')}:${path.join(home, 'emulator')}:${process.env.PATH}`,
  })
  if (!runningAndroidSerial()) {
    const avds = sh('emulator', ['-list-avds'], { env }).split('\n').map((s) => s.trim()).filter(Boolean)
    const avd = avds.find((a) => a.startsWith(avdNamePrefix))
    if (!avd) {
      throw new Error(
        `Aucun AVD nommé « ${avdNamePrefix}* » (trouvés : ${avds.join(', ') || 'aucun'}). ` +
          `Créez-en un avec le gestionnaire d'appareils d'Android Studio.`,
      )
    }
    console.log(`→ démarrage de l'émulateur ${avd}`)
    // spawn, not exec: the emulator does not exit, so anything that waits for
    // it to finish would wait forever. Detached and unref'd so this script's
    // own exit does not take the emulator down with it — a screenshot run
    // leaves the device up for the operator to look at.
    const proc = spawn('emulator', [`@${avd}`, '-no-snapshot'], {
      env, detached: true, stdio: 'ignore',
    })
    proc.unref()
    let serial = null
    for (let i = 0; i < 40 && !(serial && androidFullyBooted(serial)); i++) {
      execFileSync('sleep', ['3'])
      serial = runningAndroidSerial()
    }
    if (!serial || !androidFullyBooted(serial)) throw new Error("L'émulateur n'a pas démarré à temps.")
  }
  console.log('→ expo run:android --variant release')
  sh('npx', ['expo', 'run:android', '--variant', 'release', '--no-bundler'], {
    cwd: MOBILE, stdio: 'inherit', env,
  })
}

/**
 * Run capture.yaml on one target, returning the basenames it actually wrote
 * (03-composition may be absent — see OPTIONAL_SCREENS).
 */
function runFlow(target, { email, code, deviceArg }) {
  const outDir = path.join(ROOT, '.screenshots-tmp', target.id)
  rmSync(outDir, { recursive: true, force: true })
  mkdirSync(outDir, { recursive: true })

  // --debug-output pins where Maestro writes. `takeScreenshot` does NOT save
  // into the working directory — it files images under
  // <debug-output>/<flow>/takeScreenshot/, and by default that path carries a
  // run timestamp (~/.maestro/tests/2026-09-13_001853/…), which is no use to
  // a script that has to find them afterwards.
  const args = [
    'test', FLOW, '--debug-output', outDir,
    '-e', `EMAIL=${email}`, '-e', `CODE=${code}`,
  ]
  if (deviceArg) args.splice(1, 0, '--device', deviceArg)
  // Logged with the credential taken back out. The first run of this script
  // printed the review account's code to a terminal, and from there into a
  // chat log — a one-line convenience that leaked a production credential.
  const shown = args.map((a) => (a.startsWith('CODE=') ? 'CODE=***' : a))
  console.log(`→ maestro ${shown.join(' ')}  (cwd: ${outDir})`)
  try {
    sh(maestroBin(), args, { cwd: outDir, stdio: 'inherit' })
  } catch {
    // Node puts the whole failed command line into the Error it throws, code
    // and all — and a failure is exactly when that output gets pasted into a
    // terminal, an issue, or a chat. Masking the log line was not enough:
    // this rethrows without ever touching the original message. Maestro has
    // already printed what actually went wrong, on stdio: 'inherit'.
    throw new Error(`maestro a échoué sur la cible ${target.id} — voir sa sortie ci-dessus.`)
  }

  // --debug-output is a ROOT, not the folder: Maestro still builds
  // .maestro/tests/<timestamp>/<flow>/ underneath it. So the takeScreenshot
  // directory is found rather than assumed.
  //
  // Only that directory: the same tree also holds a screenshot per FAILED
  // command ("step-018-tapOnElement-…"), which is what diagnosed every
  // failure here so far and must never be mistaken for a store image.
  const shots = findTakeScreenshotDir(outDir)
  if (!shots) return []
  return readdirSync(shots)
    .filter((f) => f.endsWith('.png'))
    .map((f) => ({ file: path.join(shots, f), basename: path.basename(f, '.png') }))
}

/** The newest `takeScreenshot/` anywhere under `root`, or null. */
function findTakeScreenshotDir(root) {
  const found = []
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue
      const full = path.join(dir, entry.name)
      if (entry.name === 'takeScreenshot') found.push(full)
      else walk(full)
    }
  }
  if (!existsSync(root)) return null
  walk(root)
  return found.sort().pop() ?? null
}

function validateAndInstall(target, captured) {
  const missing = missingRequiredScreens(captured.map((c) => c.basename))
  if (missing.length) {
    console.warn(`  ⚠ ${target.id} : ${missing.join(', ')} n'a pas été capturé.`)
  }
  mkdirSync(target.destDir, { recursive: true })
  for (const { file, basename } of captured) {
    const dims = pngDimensions(readFileSync(file))
    if (!isPlausibleScreenshot(dims)) {
      console.warn(`  ⚠ ${target.id}/${basename} : ${dims.width}x${dims.height}, ignoré.`)
      continue
    }
    const dest = path.join(target.destDir, `${target.filePrefix}${basename}.png`)
    copyFileSync(file, dest)
    console.log(`  ✓ ${dest}  (${dims.width}x${dims.height})`)
  }
}

