function androidHome() {
  // ANDROID_HOME first: it is the one AGP recommends, and the one every other
  // path in this file is built from. ANDROID_SDK_ROOT is deprecated but still
  // the only variable some setups export — a Homebrew
  // `android-commandlinetools` install sets it and nothing else.
  const home =
    process.env.ANDROID_HOME ||
    process.env.ANDROID_SDK_ROOT ||
    path.join(process.env.HOME, 'Library/Android/sdk')
  if (!existsSync(home)) {
    throw new Error(`ANDROID_HOME introuvable (${home}). SDK Android requis pour la cible android.`)
  }
  return home
}

/**
 * The child's environment with exactly ONE Android SDK in it.
 *
 * A machine that has both Android Studio and Homebrew's
 * `android-commandlinetools` ends up exporting two different paths, and AGP
 * refuses to guess: *"Several environment variables and/or system properties
 * contain different paths to the SDK."* It stops the build outright, and the
 * message never says which one it would have preferred.
 *
 * So the deprecated variable is dropped rather than left to argue with the
 * recommended one. Same reasoning as the forced UTF-8 locale above: this
 * script owns the environment it hands to the build, and an operator's shell
 * having accumulated two SDKs over the years is not a thing to make them fix
 * before they can take a screenshot.
 */
function androidEnv(home) {
  const env = envWith({
    ANDROID_HOME: home,
    PATH: `${path.join(home, 'platform-tools')}:${path.join(home, 'emulator')}:${process.env.PATH}`,
  })
  const other = process.env.ANDROID_SDK_ROOT
  if (other && path.resolve(other) !== path.resolve(home)) {
    console.log(`→ ANDROID_SDK_ROOT (${other}) ignoré au profit de ANDROID_HOME (${home})`)
  }
  // Deleted, not blanked: an empty string is still "set" to AGP.
  delete env.ANDROID_SDK_ROOT
  return env
}

/**
 * What the Gradle daemon needs to get through `:expo-updates:kspReleaseKotlin`.
 *
 * The generated file asks for `-Xmx2048m -XX:MaxMetaspaceSize=512m`, and KSP
 * exhausts that metaspace: the build dies four minutes in with the single word
 * "Metaspace" and nothing about memory limits anywhere in the message.
 */
const GRADLE_JVMARGS = '-Xmx6g -XX:MaxMetaspaceSize=2g'

/** That value written into a gradle.properties, replacing any line already there. */
export function withGradleMemory(propertiesText, jvmargs = GRADLE_JVMARGS) {
  const line = `org.gradle.jvmargs=${jvmargs}`
  const existing = /^[ \t]*org\.gradle\.jvmargs[ \t]*=.*$/m
  if (existing.test(propertiesText)) return propertiesText.replace(existing, line)
  return `${propertiesText.replace(/\n*$/, '')}\n${line}\n`
}

/**
 * Prebuild + build + install the app once for a platform, before its
 * target(s) run. Idempotent: a second call after the first is a fast
 * incremental Xcode/Gradle build, not a full rebuild.
 */
function buildFor(platform) {
  console.log(`→ expo prebuild --clean -p ${platform}`)
  sh('npx', ['expo', 'prebuild', '--clean', '-p', platform], { cwd: MOBILE, stdio: 'inherit' })
  if (platform !== 'android') return

  // Patched here, after prebuild, rather than committed: `--clean` rewrites
  // android/ from scratch every run, so a value put in that file by hand
  // survives exactly until the next capture. This script owns both steps, so
  // it is the one place the edit can live and still be there at build time.
  //
  // A `gradle.properties` in GRADLE_USER_HOME outranks the project's, so a
  // machine that sets its own smaller value still wins — which is correct
  // (somebody said so deliberately) and worth knowing when this looks ignored.
  const props = path.join(MOBILE, 'android/gradle.properties')
  writeFileSync(props, withGradleMemory(readFileSync(props, 'utf8')))
  console.log(`→ gradle.properties : org.gradle.jvmargs=${GRADLE_JVMARGS}`)
}

/** UTF8_ENV, plus whatever the caller adds — ANDROID_HOME, a custom PATH. */
function envWith(extra) {
  return { ...UTF8_ENV, ...extra }
}

function installAndLaunchIos(udid) {
  bootIosSimulator(udid)
  console.log(`→ expo run:ios --configuration Release --device ${udid}`)
  // --no-bundler: a Release build carries its own bundle, and leaving Metro
  // running invites the app to be pointed at it instead — which would decide
  // what the screenshots show from outside the binary being shipped.
  sh('npx', ['expo', 'run:ios', '--configuration', 'Release', '--no-bundler', '--device', udid], {
    cwd: MOBILE, stdio: 'inherit',
  })
}

function installAndLaunchAndroid(avdNamePrefix) {
  const home = androidHome()
  const env = androidEnv(home)
  if (!runningAndroidSerial()) {
    const avds = sh('emulator', ['-list-avds'], { env }).split('\n').map((s) => s.trim()).filter(Boolean)
    const avd = avds.find((a) => a.startsWith(avdNamePrefix))
    if (!avd) {
      throw new Error(
        `Aucun AVD nommé « ${avdNamePrefix}* » (trouvés : ${avds.join(', ') || 'aucun'}). ` +
          `Créez-en un avec le gestionnaire d'appareils d'Android Studio.`,
      )
    }
    console.log(`→ démarrage de l'émulateur ${avd}`)
    // spawn, not exec: the emulator does not exit, so anything that waits for
    // it to finish would wait forever. Detached and unref'd so this script's
    // own exit does not take the emulator down with it — a screenshot run
    // leaves the device up for the operator to look at.
    const proc = spawn('emulator', [`@${avd}`, '-no-snapshot'], {
      env, detached: true, stdio: 'ignore',
    })
    proc.unref()
    let serial = null
    for (let i = 0; i < 40 && !(serial && androidFullyBooted(serial)); i++) {
      execFileSync('sleep', ['3'])
      serial = runningAndroidSerial()
    }
    if (!serial || !androidFullyBooted(serial)) throw new Error("L'émulateur n'a pas démarré à temps.")
  }
  assertAndroidJdk()
  uninstallAndroidApp(env)
  console.log('→ expo run:android --variant release')
  sh('npx', ['expo', 'run:android', '--variant', 'release', '--no-bundler'], {
    cwd: MOBILE, stdio: 'inherit', env,
  })
}

/**
 * Run capture.yaml on one target, returning the basenames it actually wrote —
 * which is every REQUIRED_SCREENS entry, or the run is not shippable.
 */
function runFlow(target, { email, code, deviceArg }) {
  const outDir = path.join(ROOT, '.screenshots-tmp', target.id)
  rmSync(outDir, { recursive: true, force: true })
  mkdirSync(outDir, { recursive: true })

  // --debug-output pins where Maestro writes. `takeScreenshot` does NOT save
  // into the working directory — it files images under
  // <debug-output>/<flow>/takeScreenshot/, and by default that path carries a
  // run timestamp (~/.maestro/tests/2026-09-13_001853/…), which is no use to
  // a script that has to find them afterwards.
  const args = [
    'test', FLOW, '--debug-output', outDir,
    '-e', `EMAIL=${email}`, '-e', `CODE=${code}`,
    '-e', `ORIENTATION=${target.orientation}`,
    // Which of the two player paths the flow walks. Passed by the target
    // rather than sniffed from a tablet-only element: the device class is
    // something this script already knows, and a flow guessing at it would be
    // one more thing that can be wrong quietly.
    '-e', `TWO_PANE=${target.twoPane}`,
  ]
  if (deviceArg) args.splice(1, 0, '--device', deviceArg)
  // Logged with the credential taken back out. The first run of this script
  // printed the review account's code to a terminal, and from there into a
  // chat log — a one-line convenience that leaked a production credential.
  const shown = args.map((a) => (a.startsWith('CODE=') ? 'CODE=***' : a))
  console.log(`→ maestro ${shown.join(' ')}  (cwd: ${outDir})`)
  try {
    sh(maestroBin(), args, { cwd: outDir, stdio: 'inherit' })
  } catch {
    // Node puts the whole failed command line into the Error it throws, code
    // and all — and a failure is exactly when that output gets pasted into a
    // terminal, an issue, or a chat. Masking the log line was not enough:
    // this rethrows without ever touching the original message. Maestro has
    // already printed what actually went wrong, on stdio: 'inherit'.
    throw new Error(`maestro a échoué sur la cible ${target.id} — voir sa sortie ci-dessus.`)
  }

  // --debug-output is a ROOT, not the folder: Maestro still builds
  // .maestro/tests/<timestamp>/<flow>/ underneath it. So the takeScreenshot
  // directory is found rather than assumed.
  //
  // Only that directory: the same tree also holds a screenshot per FAILED
  // command ("step-018-tapOnElement-…"), which is what diagnosed every
  // failure here so far and must never be mistaken for a store image.
  const shots = findTakeScreenshotDir(outDir)
  if (!shots) return []
  return readdirSync(shots)
    .filter((f) => f.endsWith('.png'))
    .map((f) => ({ file: path.join(shots, f), basename: path.basename(f, '.png') }))
}

/** The newest `takeScreenshot/` anywhere under `root`, or null. */
function findTakeScreenshotDir(root) {
  const found = []
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue
      const full = path.join(dir, entry.name)
      if (entry.name === 'takeScreenshot') found.push(full)
      else walk(full)
    }
  }
  if (!existsSync(root)) return null
  walk(root)
  return found.sort().pop() ?? null
}

/**
 * The same PNG without the metadata that claims it needs rotating.
 *
 * `sips -r` rotates the PIXELS — the IHDR comes back 2752x2064 — and then also
 * writes `Orientation = 8` into an `eXIf` chunk and into the XMP. A reader that
 * honours either turns the image a second time, so the file is upright in one
 * viewer and on its side in the next. App Store Connect honours it: the iPad
 * screenshots went up correctly sized and displayed sideways on the product
 * page.
 *
 * Both carriers go. An absent tag means orientation 1, which is what a
 * correctly-rotated file should have said in the first place. Chunks are
 * copied verbatim, so their CRCs stay valid; only the ancillary ones named
 * here are dropped, and a store screenshot needs neither.
 *
 * @param {Buffer} buf
 */
export function pngWithoutOrientationMetadata(buf) {
  const sig = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])
  if (buf.length < 8 || !buf.subarray(0, 8).equals(sig)) throw new Error('not a PNG')
  const kept = [buf.subarray(0, 8)]
  let pos = 8
  while (pos + 8 <= buf.length) {
    const length = buf.readUInt32BE(pos)
    const type = buf.subarray(pos + 4, pos + 8).toString('latin1')
    const end = pos + 12 + length
    const data = buf.subarray(pos + 8, pos + 8 + length)
    // The XMP packet rides in an iTXt whose keyword says so; other iTXt
    // chunks are somebody else's and are left alone.
    const isXmp = type === 'iTXt' && data.subarray(0, 17).toString('latin1') === 'XML:com.adobe.xmp'
    if (type !== 'eXIf' && !isXmp) kept.push(buf.subarray(pos, end))
    pos = end
    if (type === 'IEND') break
  }
  return Buffer.concat(kept)
}

/**
 * Turn a sideways capture the right way up, in place.
 *
 * Maestro's `setOrientation` rotates the app's interface but not the
 * simulator's display: after it, `takeScreenshot` hands back a PORTRAIT PNG
 * whose content is a landscape render lying on its side. Rotating the
 * container is therefore not a fudge — it is the only thing still wrong with
 * the image, and the rotation is lossless.
 *
 * `sips` ships with macOS, and the only targets that ask for this are iOS
 * simulators, which do not run anywhere else.
 */
function uprightLandscape(file) {
  // -90 = counter-clockwise, which is what LANDSCAPE_LEFT needs: the status
  // bar comes back along the right edge, and that edge is the top.
  sh('sips', ['-r', '-90', file], { stdio: ['ignore', 'ignore', 'pipe'] })
  // …and take back sips's claim that it still needs turning.
  writeFileSync(file, pngWithoutOrientationMetadata(readFileSync(file)))
}

function validateAndInstall(target, captured) {
  const wanted = screensFor(target)
  const missing = missingRequiredScreens(captured.map((c) => c.basename), wanted)
  if (missing.length) {
    console.warn(`  ⚠ ${target.id} : ${missing.join(', ')} n'a pas été capturé.`)
  }
  mkdirSync(target.destDir, { recursive: true })
  const keep = new Set(wanted)
  for (const { file, basename } of captured) {
    // Captured but not wanted here — the flow is one file for every target.
    // Said out loud rather than passed over: a silent drop and a silent
    // failure look the same in a log.
    if (!keep.has(basename)) {
      console.log(`  — ${target.id}/${basename} : hors du jeu de cette cible.`)
      continue
    }
    if (target.orientation !== 'PORTRAIT') uprightLandscape(file)
    const dims = pngDimensions(readFileSync(file))
    if (!isPlausibleScreenshot(dims, target.orientation)) {
      console.warn(
        `  ⚠ ${target.id}/${basename} : ${dims.width}x${dims.height}, ` +
          `attendu ${target.orientation.toLowerCase()}, ignoré.`,
      )
      continue
    }
    const dest = path.join(target.destDir, `${target.filePrefix}${basename}.png`)
    copyFileSync(file, dest)
    console.log(`  ✓ ${dest}  (${dims.width}x${dims.height})`)
  }
}

