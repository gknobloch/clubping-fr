// CocoaPods (invoked by `expo prebuild`) calls String#unicode_normalize on a
// path, which Ruby refuses under the "C" locale — the default for a shell
// with no LANG set, which is every non-interactive one. Without this,
// prebuild dies mid-pod-install with "Unicode Normalization not appropriate
// for ASCII-8BIT", a Ruby error with nothing about locales in it. Already
// worked around once for `store:fastlane` (see mobile/package.json); this is
// the same fix for the other command that shells out to CocoaPods.
const UTF8_ENV = { ...process.env, LANG: 'fr_FR.UTF-8', LC_ALL: 'fr_FR.UTF-8' }

/**
 * Where maestro actually is.
 *
 * Its installer drops the binary in ~/.maestro/bin and appends that to
 * .zshrc / .bash_profile — neither of which a non-interactive child process
 * reads. So a shell where `maestro` works by hand still spawns ENOENT from
 * here, which is exactly how this failed the first time it ran.
 */
function maestroBin() {
  const candidates = [
    process.env.MAESTRO_BIN,
    path.join(process.env.HOME ?? '', '.maestro/bin/maestro'),
  ].filter(Boolean)
  for (const c of candidates) if (existsSync(c)) return c
  return 'maestro' // already on PATH, or about to fail with a clear message
}

function sh(cmd, args, opts = {}) {
  return execFileSync(cmd, args, { encoding: 'utf8', env: UTF8_ENV, ...opts })
}

/**
 * The UDID of the newest-runtime instance of a named iOS simulator, already
 * booted if one is, otherwise the newest available.
 */
function resolveIosSimulator(name) {
  const list = JSON.parse(sh('xcrun', ['simctl', 'list', '-j', 'devices', 'available']))
  const candidates = []
  for (const [runtime, devices] of Object.entries(list.devices)) {
    for (const d of devices) {
      if (d.name === name) candidates.push({ runtime, udid: d.udid, state: d.state })
    }
  }
  if (!candidates.length) {
    throw new Error(
      `Aucun simulateur « ${name} » installé. Xcode → Settings → Platforms, ou ` +
        `\`xcrun simctl list devicetypes\` pour voir ce qui existe.`,
    )
  }
  const booted = candidates.find((c) => c.state === 'Booted')
  if (booted) return booted.udid
  // Runtime identifiers sort lexicographically the same as version order
  // (iOS-26-4 < iOS-26-5), which is the only ordering that matters here.
  candidates.sort((a, b) => b.runtime.localeCompare(a.runtime))
  return candidates[0].udid
}

function bootIosSimulator(udid) {
  try {
    // stderr captured rather than inherited: booting an already-booted
    // simulator is the normal case under --skip-build, and simctl's error
    // about it is noise the operator should not have to learn to ignore.
    sh('xcrun', ['simctl', 'boot', udid], { stdio: ['ignore', 'ignore', 'pipe'] })
  } catch (e) {
    // "Unable to boot device in current state: Booted" — already running is
    // success, not a failure worth stopping for.
    if (!String(e.stderr ?? e.message).includes('current state: Booted')) throw e
  }
}

function adbPath() {
  return process.env.ANDROID_HOME
    ? path.join(process.env.ANDROID_HOME, 'platform-tools/adb')
    : 'adb'
}

/** The already-running Android emulator's adb serial, or null. */
function runningAndroidSerial() {
  const out = sh(adbPath(), ['devices'])
  const line = out.split('\n').find((l) => /^emulator-\d+\s+device$/.test(l.trim()))
  return line ? line.trim().split(/\s+/)[0] : null
}

/** `adb devices` reports a device the moment it starts booting, long before
 *  it can install an app — this is the check that actually means "ready". */
function androidFullyBooted(serial) {
  try {
    return sh(adbPath(), ['-s', serial, 'shell', 'getprop', 'sys.boot_completed']).trim() === '1'
  } catch {
    return false
  }
}

